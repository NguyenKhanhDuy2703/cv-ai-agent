import re
from typing import List, Optional, Set, Tuple



class AntiHallucinationGuard:
    """
    Code-based verification rule to ensure no numbers, dates, or metrics
    generated by the LLM are fabricated out of nowhere.
    """

    @staticmethod
    def extract_numbers_and_metrics(text: str) -> Set[str]:
        """
        Extract numerical tokens, percentages, and metrics: e.g., '12', '20%', '$50k', '2021'.
        """
        pattern = r"\b(?:\$|€|£)?\d+(?:[.,]\d+)?%?(?:k|m|b)?\b"
        matches = re.findall(pattern, text, flags=re.IGNORECASE)
        return {m.strip().lower() for m in matches}

    @classmethod
    def verify_facts(cls, output_text: str, source_texts: List[str]) -> Tuple[bool, List[str]]:
        """
        Check that every metric/number in output_text can be traced back to at least one source text.
        Returns (is_valid, list_of_unverified_metrics).
        """
        output_metrics = cls.extract_numbers_and_metrics(output_text)
        if not output_metrics:
            return True, []

        source_combined = " ".join(source_texts).lower()
        unverified = []

        for metric in output_metrics:
            clean_metric = metric.lower()
            if clean_metric not in source_combined:
                unverified.append(metric)

        return (len(unverified) == 0, unverified)

    @classmethod
    def verify_bullet(
        cls,
        output_text: str,
        source_texts: List[str],
        ban_terms: Optional[List[str]] = None,
    ) -> Tuple[bool, List[str]]:
        """
        Comprehensive verification of rewritten bullet:
        1. Metrics/numbers must exist in sources.
        2. Banned terms must not appear.
        3. Text must not be empty.
        Returns (is_valid, list_of_violations).
        """
        violations: List[str] = []
        if not output_text.strip():
            return False, ["Rewritten bullet cannot be empty"]

        # 1. Fact checking (numbers/metrics)
        is_valid_facts, unverified = cls.verify_facts(output_text, source_texts)
        if not is_valid_facts:
            violations.extend([f"Unverified metric/number: '{m}'" for m in unverified])

        # 2. Ban terms check
        if ban_terms:
            text_lower = output_text.lower()
            for term in ban_terms:
                if term.strip() and term.lower() in text_lower:
                    violations.append(f"Forbidden term detected: '{term}'")

        return (len(violations) == 0, violations)

